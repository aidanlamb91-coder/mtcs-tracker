"""Bundle packs/*.json into js/packs.generated.js so index.html works from file:// (no fetch at runtime).
Run after editing any pack:  python3 tools/build-data.py"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
cat = json.loads((root / "packs/index.json").read_text(encoding="utf-8"))
packs = {}
for p in cat["packs"]:
    if p.get("file"):
        packs[p["id"]] = json.loads((root / "packs" / p["file"]).read_text(encoding="utf-8"))
out = ("// GENERATED by tools/build-data.py from packs/*.json. Do not edit by hand.\n"
       "window.PACK_CATALOGUE = " + json.dumps(cat["packs"], ensure_ascii=False) + ";\n"
       "window.PACKS = " + json.dumps(packs, ensure_ascii=False, indent=1) + ";\n")
(root / "js/packs.generated.js").write_text(out, encoding="utf-8")
print("wrote js/packs.generated.js with", len(packs), "active pack(s)")
